def generate_business_domain_map(output: Path, domain_counter: Counter[str], grouped: dict[str, list[FileInfo]]) -> None:
    rows = []
    for domain, count in domain_counter.most_common(80):
        if domain == "unknown":
            continue
        files = grouped.get(domain, [])
        controllers = [f for f in files if f.role == "controller"]
        mq_files = [f for f in files if f.role == "mq-consumer" or f.is_mq_consumer_custom]
        repos = [f for f in files if f.role == "repository" or f.tables]
        risks = sorted({signal for f in files for signal in f.risk_signals})
        evidence = []
        for bucket in (controllers, mq_files, repos, files):
            for item in bucket:
                if item.class_name:
                    evidence.append(f"{item.class_name} ({item.path})")
                if len(evidence) >= 3:
                    break
            if len(evidence) >= 3:
                break
        rows.append([
            domain, str(count),
            ", ".join(sorted({f.role for f in files})) or "-",
            "; ".join(evidence) or "需要从索引继续确认",
            ", ".join(risks) or "-",
        ])
    write(output / "05_indexes" / "business_domain_map.md", f"""# Business Domain Map

本文件是自动生成的业务域候选地图。用于帮助 AI 从新需求定位候选业务域。

## 使用方式

1. 从需求中提取业务名词、动作、状态、接口、表、消息、Job 名称
2. 在下表中寻找最接近的业务域
3. 读取 `01_business_domains/<业务域>/skill.md`

{md_table(["候选业务域", "文件数", "角色覆盖", "证据入口", "风险信号"], rows, 80)}
""")


