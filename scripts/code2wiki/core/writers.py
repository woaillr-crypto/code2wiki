def generate_domain_docs(output: Path, domain: str, files: list[FileInfo], ctx: ProjectContext,
                         mybatis_xmls: list[MyBatisXmlInfo] | None = None) -> None:
    domain_dir = output / "01_business_domains" / domain
    by_role: dict[str, list[FileInfo]] = defaultdict(list)
    for item in files:
        by_role[item.role].append(item)

    # ── skill.md（域入口，最重要的文件） ──────────────────────────────
    controllers = by_role.get("controller", [])
    services = by_role.get("service", [])
    mq_consumers = by_role.get("mq-consumer", [])
    schedulers = by_role.get("scheduler", [])
    entities = by_role.get("entity", [])
    repos = by_role.get("repository", [])
    enums = by_role.get("enum", [])
    ext_clients = by_role.get("external-client", [])
    caches = by_role.get("cache", [])

    # 统计
    role_stats = ", ".join(f"{role_label(r)} {len(fs)}" for r, fs in sorted(by_role.items()) if fs)

    # API 路径
    api_paths = []
    for f in controllers:
        api_paths.extend(f.mappings)
    api_summary = "\n".join(f"- `{p}`" for p in api_paths[:15]) if api_paths else "- 无直接 API 入口"

    # 表名
    all_tables = sorted({t for f in files for t in f.tables})
    table_summary = ", ".join(f"`{t}`" for t in all_tables[:10]) if all_tables else "无直接表注解（可能通过 RPC 访问数据层）"

    # MQ 消费者
    mq_items = []
    for f in mq_consumers:
        mq_items.append(f"- `{f.class_name or f.path}` — {f.class_doc or '需要确认业务含义'}")
    for f in files:
        if f.is_mq_consumer_custom and f.role != "mq-consumer":
            mq_items.append(f"- `{f.class_name or f.path}` (Producer 中包含 MQ Handle 引用)")
    mq_summary = "\n".join(mq_items[:10]) if mq_items else "- 未检测到 MQ 消费者"

    # MQ 生产者
    producer_files = [f for f in files if f.is_mq_producer]
    producer_summary = "\n".join(f"- `{f.class_name}` ({f.path})" for f in producer_files[:5]) if producer_files else "- 未检测到 MQ 发送"

    # 定时任务
    job_items = []
    for f in schedulers:
        job_names = ", ".join(f.xxl_jobs) if f.xxl_jobs else ", ".join(f.scheduled) if f.scheduled else "检测到调度角色"
        job_items.append(f"- `{f.class_name or f.path}`: {job_names}")
    job_summary = "\n".join(job_items[:10]) if job_items else "- 未检测到定时任务"

    # Dubbo RPC 依赖
    dubbo_refs_all = sorted({ref for f in files for ref in f.dubbo_refs})
    dubbo_summary = "\n".join(f"- `{r}`" for r in dubbo_refs_all[:10]) if dubbo_refs_all else ""

    # Feign RPC 依赖
    feign_items = []
    for f in files:
        if f.feign_detail and f.feign_detail.get("service"):
            svc = f.feign_detail["service"]
            path = f.feign_detail.get("path", "")
            path_info = f" path=`{path}`" if path else ""
            feign_items.append(f"- `{f.class_name}` → **{svc}**{path_info}")
    feign_summary = "\n".join(feign_items[:10]) if feign_items else ""

    # 合成 RPC 依赖段落
    rpc_section = ""
    if dubbo_summary or feign_summary:
        if dubbo_summary:
            rpc_section += "### Dubbo RPC\n\n" + dubbo_summary + "\n\n"
        if feign_summary:
            rpc_section += "### Feign HTTP\n\n" + feign_summary + "\n\n"
    else:
        rpc_section = "- 未检测到 RPC 依赖\n"

    # 风险信号
    all_risks = sorted({s for f in files for s in f.risk_signals})
    risk_summary = ", ".join(all_risks) if all_risks else "无明显风险信号"

    # 关键文件
    key_files = sorted(files, key=lambda f: (
        f.role != "controller",
        f.role != "service",
        f.role != "mq-consumer",
        f.role != "scheduler",
        f.path,
    ))[:20]
    key_table = md_table(
        ["角色", "类", "说明", "文件"],
        [[role_label(f.role), f.class_name or "-", f.class_doc or "-", f.path] for f in key_files],
        20,
    )

    write(domain_dir / "skill.md", f"""# {domain} 业务域

## 何时使用

当需求、缺陷或排查涉及以下关键词时使用本域文档：`{domain}`、{', '.join(f'`{p}`' for p in api_paths[:5])}

## 文件统计

{role_stats}，共 {len(files)} 个文件

## API 入口

{api_summary}

## 关联数据表

{table_summary}

## MQ 消费者

{mq_summary}

## MQ 发送

{producer_summary}

## 定时任务

{job_summary}

## RPC 依赖

{rpc_section}
## 风险信号

{risk_summary}

## 核心文件清单

{key_table}

## 修改前检查

- **权限**：检查 Controller 的拦截器、注解和用户上下文
- **事务**：优先阅读带 `@Transactional` 的 Service/Manager
- **幂等**：检查唯一键、业务单号、回调/消息重复消费
- **并发**：检查锁、状态流转、库存/余额/次数类扣减
- **缓存**：检查 Redis、Cache 注解和缓存失效时机
- **兼容性**：检查枚举、状态码、历史数据和外部接口契约
""")

    # ── concepts.md（有数据填充） ──────────────────────────────
    # Entity/DTO 字段
    field_rows = []
    for f in files:
        if f.fields and f.role in ("entity", "dto", "other"):
            for fld in f.fields[:15]:
                field_rows.append([f.class_name or "-", fld["name"], fld["type"], f.path])

    # 枚举值
    enum_rows = []
    for f in files:
        if f.enum_values:
            vals = ", ".join(f.enum_values[:10])
            if len(f.enum_values) > 10:
                vals += f" ... (共{len(f.enum_values)}个)"
            enum_rows.append([f.class_name or "-", vals, f.path])

    concepts_content = f"# {domain} 核心概念\n\n"

    if field_rows:
        concepts_content += "## Entity/DTO 字段\n\n"
        concepts_content += md_table(["类", "字段", "类型", "文件"], field_rows, 60)
        concepts_content += "\n\n"
    else:
        concepts_content += "## Entity/DTO 字段\n\n本域未检测到带字段的 Entity/DTO，可能数据模型在独立的 data 模块中。\n\n"

    if enum_rows:
        concepts_content += "## 枚举/状态值\n\n"
        concepts_content += md_table(["枚举类", "常量值", "文件"], enum_rows, 30)
        concepts_content += "\n\n"

    concepts_content += "## 业务术语映射\n\n"
    concepts_content += "根据代码中的类名推断的候选术语（需人工校准）：\n\n"
    seen_concepts = set()
    for f in files:
        if f.class_name and f.role in ("entity", "dto", "enum", "service"):
            base = f.class_name
            for suffix in CLASS_SUFFIXES:
                if base.endswith(suffix):
                    base = base[:-len(suffix)]
                    break
            if base and base not in seen_concepts and len(base) > 2:
                seen_concepts.add(base)
    for concept in sorted(seen_concepts)[:20]:
        concepts_content += f"- `{concept}` → 需要确认业务含义\n"

    write(domain_dir / "concepts.md", concepts_content)

    # ── api_map.md ──────────────────────────────
    api_rows = []
    for f in controllers:
        mappings = ", ".join(f.mappings) if f.mappings else "-"
        api_rows.append([mappings, f.class_name or "-", f.class_doc or "需要补充", f.path])
    write(domain_dir / "api_map.md", f"# {domain} API Map\n\n"
          + md_table(["接口路径", "Controller", "说明", "文件"], api_rows, 200))

    # ── db_map.md（有数据填充） ──────────────────────────────
    db_rows = []
    for f in files:
        if f.role in ("entity", "repository") or f.tables:
            db_rows.append([", ".join(f.tables) or "-", f.class_name or "-", role_label(f.role), f.path])

    # Entity 字段详情
    entity_field_sections = ""
    for f in files:
        if f.fields and f.role == "entity":
            entity_field_sections += f"\n### {f.class_name} (`{f.path}`)\n\n"
            entity_field_sections += md_table(
                ["字段", "类型"],
                [[fld["name"], fld["type"]] for fld in f.fields[:25]],
            )
            entity_field_sections += "\n"

    db_content = f"# {domain} DB Map\n\n"
    if db_rows:
        db_content += md_table(["表/注解", "类", "角色", "文件"], db_rows, 200) + "\n\n"
    else:
        db_content += "未检测到直接的表注解或 Entity/Mapper。数据访问可能通过 Dubbo RPC 调用独立的 data 模块。\n\n"
        if dubbo_refs_all:
            db_content += "### 通过 RPC 引用的数据服务\n\n"
            for ref in dubbo_refs_all[:15]:
                if "rpc" in ref.lower() or "service" in ref.lower():
                    db_content += f"- `{ref}`\n"
            db_content += "\n"
    if entity_field_sections:
        db_content += "## Entity 字段详情\n" + entity_field_sections

    # MyBatis XML 表信息
    if mybatis_xmls:
        # 按 namespace 中的关键词匹配域
        domain_xmls = []
        for mx in mybatis_xmls:
            ns_lower = mx.namespace.lower()
            # 域名出现在 namespace 中
            if domain.replace("-", "") in ns_lower or domain.replace("-", ".") in ns_lower:
                domain_xmls.append(mx)
            else:
                # 或者 Mapper 类名与域内文件匹配
                ns_class = mx.namespace.split(".")[-1] if "." in mx.namespace else mx.namespace
                for f in files:
                    if f.class_name and f.class_name == ns_class:
                        domain_xmls.append(mx)
                        break
        if domain_xmls:
            db_content += "## MyBatis XML 映射\n\n"
            for mx in domain_xmls[:10]:
                tables_str = ", ".join(f"`{t}`" for t in mx.tables[:8]) if mx.tables else "需确认"
                sql_count = len(mx.sql_ids)
                db_content += f"### `{mx.namespace}` — `{mx.path}`\n\n"
                db_content += f"- 关联表：{tables_str}\n"
                db_content += f"- SQL 操作数：{sql_count}\n"
                if mx.sql_ids:
                    db_content += f"- 操作列表：{', '.join(mx.sql_ids[:8])}"
                    if sql_count > 8:
                        db_content += f" ... (共{sql_count}个)"
                    db_content += "\n"
                db_content += "\n"

    write(domain_dir / "db_map.md", db_content)

    # ── code_entrypoints.md ──────────────────────────────
    entry_rows = [[role_label(f.role), f.class_name or "-", f.class_doc or "-", f.path, ", ".join(f.risk_signals) or "-"]
                  for f in sorted(files, key=lambda x: (x.role, x.path))]
    write(domain_dir / "code_entrypoints.md",
          f"# {domain} Code Entrypoints\n\n"
          + md_table(["角色", "类", "说明", "文件", "风险信号"], entry_rows, 300))

    # ── integration_map.md（增强版） ──────────────────────────────
    integration_rows = []
    for f in files:
        has_integration = (f.mq_listeners or f.scheduled or f.feign_clients or f.dubbo_refs or
                          f.role in {"external-client", "mq-consumer", "scheduler"} or
                          f.is_mq_producer or f.is_mq_consumer_custom)
        if has_integration:
            integration_rows.append([
                f.class_name or "-",
                role_label(f.role),
                "是" if (f.is_mq_consumer_custom or f.mq_listeners) else "-",
                "是" if f.is_mq_producer else "-",
                ", ".join(f.scheduled) or "-",
                ", ".join(f.feign_clients) or "-",
                ", ".join(f.dubbo_refs[:3]) or "-",
                f.path,
            ])
    write(domain_dir / "integration_map.md",
          f"# {domain} Integration Map\n\n"
          + md_table(["类", "角色", "MQ消费", "MQ发送", "定时任务", "Feign", "Dubbo RPC", "文件"],
                     integration_rows, 200))

    # ── workflows.md（基于方法签名的流程线索） ──────────────────────────────
    wf_content = f"# {domain} Workflows\n\n"
    wf_content += "## 基于代码结构推断的流程线索\n\n"
    wf_content += "以下是从 Controller/Service/MQ Consumer 的 public 方法签名中提取的候选流程，需要结合源码确认真实业务语义。\n\n"

    has_methods = False
    for f in sorted(files, key=lambda x: (x.role != "controller", x.role != "service", x.role != "mq-consumer")):
        if f.public_methods:
            has_methods = True
            wf_content += f"### {f.class_name} ({role_label(f.role)}) — `{f.path}`\n\n"
            if f.class_doc:
                wf_content += f"> {f.class_doc}\n\n"
            method_rows = [[m["name"], m["return_type"], m["params"][:100]] for m in f.public_methods[:15]]
