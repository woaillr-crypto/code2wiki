def build_keyword_domain_map(top_domains: list[str], grouped: dict[str, list]) -> str:
    """构建需求关键词→域的快速定位表。从 API 路径、类名、MQ Consumer、方法名、class_doc、枚举名中提取。"""
    rows: list[list[str]] = []
    for domain in top_domains[:25]:
        files = grouped.get(domain, [])
        if not files:
            continue
        biz_words: dict[str, int] = {}  # word -> frequency

        def add_word(w: str, weight: int = 1) -> None:
            wl = w.lower().strip()
            if wl and len(wl) > 2:
                biz_words[wl] = biz_words.get(wl, 0) + weight

        # 域名本身（最高权重）
        for part in domain.split("-"):
            add_word(part, 10)

        for f in files:
            # API 路径中的业务词
            for mapping in f.mappings[:5]:
                for seg in mapping.strip("/").split("/"):
                    if seg and seg not in {"<class-level>", "api", "v1", "v2", "admin", "internal"}:
                        add_word(seg, 3)

            # MQ Consumer 类名中的业务词（权重高）
            if f.role == "mq-consumer" and f.class_name:
                for w in _extract_business_words(f.class_name):
                    add_word(w, 4)

            # 定时任务名
            for job in f.xxl_jobs:
                for w in _extract_business_words(job):
                    add_word(w, 3)

            # Service/Controller 的核心方法名
            if f.role in ("controller", "service") and f.public_methods:
                for m in f.public_methods[:5]:
                    for w in _extract_business_words(m["name"]):
                        add_word(w, 2)

            # class_doc 中的关键词
            if f.class_doc:
                for w in re.findall(r"[\u4e00-\u9fff]+", f.class_doc):  # 中文词
                    add_word(w, 3)
                for w in _extract_business_words(f.class_doc):
                    add_word(w, 1)

            # 枚举类名中的业务词
            if f.role == "enum" and f.class_name:
                for w in _extract_business_words(f.class_name):
                    add_word(w, 2)

        # 排序取 top keywords
        sorted_kw = sorted(biz_words.items(), key=lambda x: -x[1])
        top_kw = [kw for kw, _ in sorted_kw if kw != domain][:6]

        # 首先阅读的文件
        first_file = ""
        for role_pref in ("controller", "service", "mq-consumer"):
            for f in files:
                if f.role == role_pref and f.class_name:
                    first_file = f.class_name
                    break
            if first_file:
                break

        display_kw = [domain] + top_kw[:4]
        rows.append([", ".join(display_kw), domain, first_file or "-"])
    if not rows:
        return ""
    return md_table(["需求关键词", "定位域", "首先阅读"], rows, 25)


def build_mermaid_domain_graph(java_infos: list, top_domains: list[str]) -> str:
    """构建 Mermaid 域间依赖图。"""
    # 收集域间调用关系
    edges: dict[tuple[str, str], set[str]] = defaultdict(set)
    # 建立类名→域的映射
    class_to_domain: dict[str, str] = {}
    for info in java_infos:
        if info.class_name and info.domain in top_domains:
            class_to_domain[info.class_name] = info.domain
            # 也映射小写首字母版本（变量名常用）
            lower_first = info.class_name[0].lower() + info.class_name[1:]
            class_to_domain[lower_first] = info.domain

    for info in java_infos:
        if info.domain not in top_domains or info.domain == "unknown":
            continue
        for ct in info.call_targets:
            target_cls = ct["target_class"]
            target_domain = class_to_domain.get(target_cls)
            if target_domain and target_domain != info.domain and target_domain in top_domains:
                edges[(info.domain, target_domain)].add(ct["method"])

    if not edges:
        return ""

    # 只保留 top 12 条边，按调用方法数排序
    sorted_edges = sorted(edges.items(), key=lambda x: -len(x[1]))[:12]

    lines = ["```mermaid", "graph LR"]
    for (src, dst), methods in sorted_edges:
        src_id = src.replace("-", "_")
        dst_id = dst.replace("-", "_")
        count = len(methods)
        lines.append(f"  {src_id}[{src}] -->|{count}次调用| {dst_id}[{dst}]")
    lines.append("```")
    return "\n".join(lines)


def generate_root_skill(output: Path, project: Path, top_domains: list[str],
                        java_infos: list | None = None, grouped: dict | None = None) -> None:
    skill_name = skill_name_from_project(project)
    top = "、".join(top_domains[:12]) if top_domains else "候选业务域"

    # 构建需求定位快速通道
    keyword_table = ""
    if grouped:
        keyword_table = build_keyword_domain_map(top_domains, grouped)

    # 构建 Mermaid 域间依赖图
    mermaid_graph = ""
    if java_infos:
        mermaid_graph = build_mermaid_domain_graph(java_infos, top_domains)

    keyword_section = ""
    if keyword_table:
        keyword_section = f"""
## 需求定位快速通道

收到需求后，用需求中的关键词在下表中快速匹配业务域：

{keyword_table}
"""

    mermaid_section = ""
    if mermaid_graph:
        mermaid_section = f"""
## 域间依赖关系

{mermaid_graph}
"""

    write(output / "SKILL.md", f"""---
name: {skill_name}
description: {project.name} 项目的业务上下文 skill。用于让 AI 基于 Business Context Layer 理解该 Java/Spring 后端项目，并在新需求开发、缺陷排查、接口变更、数据库字段变更、MQ/Job 改造、业务流程调整时快速定位业务域、核心入口、数据模型、集成依赖和风险点。候选业务域包括：{top}。
---

# {project.name} Business Context Skill

## 使用目标

使用本 skill 时，先通过业务语义定位需求，再阅读精确代码。不要直接全局搜索后开始改代码；必须先建立"需求 -> 业务域 -> 流程 -> 入口 -> 数据 -> 风险 -> 测试"的链路。
{keyword_section}
## 新需求处理流程

1. 读取 `00_project_overview.md`，了解系统定位、模块、候选业务域和核心风险。
2. **用上面的"需求定位快速通道"或 `05_indexes/business_domain_map.md`** 定位候选业务域。
3. 读取候选业务域的 `01_business_domains/<domain>/skill.md`（每个域最重要的入口文件）。
4. 读取 `call_chains.md` 了解调用关系，再按需深入 `workflows.md`、`concepts.md` 等。
5. 根据映射中的文件路径回到源码阅读。
6. 修改代码前检查权限、事务、幂等、并发、缓存、状态机、外部接口、历史数据兼容和测试影响。
7. 完成需求后更新对应领域文档和相关索引。
{mermaid_section}
## 快速入口

- 项目总览：`00_project_overview.md`
- 业务域地图：`05_indexes/business_domain_map.md`
- 域间调用图：`05_indexes/call_graph.md`
- API 索引：`05_indexes/api_index.md`
- 代码入口索引：`05_indexes/code_entrypoint_index.md`
- Git 活跃度：`05_indexes/git_activity.md`（热点文件、域活跃度、贡献者）
- 可选辅助知识：`06_auxiliary_knowledge/auxiliary_knowledge.md`

## 上下文加载策略（L0/L1/L2）

- **L0**：先加载项目总览、需求定位快速通道、术语表。
- **L1**：只加载命中的业务域 `skill.md` + `call_chains.md`。
- **L2**：再加载该业务域的 workflows/concepts/API/DB/integration/risk/examples。
- **Source**：最后阅读 L2 指向的源码文件。
""")


