def extract_auxiliary_summary(path: Path, root: Path) -> dict[str, str]:
    text = read_text(path, limit=16_000)
    title, description = "", ""
    headings = []
    for line in text.splitlines()[:240]:
        stripped = line.strip()
        if not title and stripped.startswith("#"):
            title = stripped.lstrip("#").strip()
        if stripped.startswith("description:") and not description:
            description = stripped.split(":", 1)[1].strip().strip("|").strip()
        if stripped.startswith("#"):
            headings.append(stripped[:120])
        if len(headings) >= 8:
            break
    return {
        "path": rel(path, root),
        "source": path.parts[len(root.parts)] if len(path.parts) > len(root.parts) else path.parts[0],
        "title": title or path.stem,
        "description": description,
        "headings": " / ".join(headings),
    }


